def P(t, st=B):
    return Paragraph(t, st)


def bullets(items):
    return [Paragraph(x, BUL, bulletText='•') for x in items]


def table(rows, widths, head_rows=1, style_extra=(), font=C, bold_first_col=False):
    data = []
    for i, r in enumerate(rows):
        data.append([c if not isinstance(c, str) else
                     Paragraph(c, CB if (i < head_rows or (bold_first_col and j == 0)) else font)
                     for j, c in enumerate(r)])
    t = Table(data, colWidths=widths, repeatRows=head_rows)
    st = [('GRID', (0, 0), (-1, -1), 0.4, RULE), ('BACKGROUND', (0, 0), (-1, head_rows - 1), HEAD),
          ('VALIGN', (0, 0), (-1, -1), 'TOP'), ('LEFTPADDING', (0, 0), (-1, -1), 3),
          ('RIGHTPADDING', (0, 0), (-1, -1), 3), ('TOPPADDING', (0, 0), (-1, -1), 2),
          ('BOTTOMPADDING', (0, 0), (-1, -1), 2)]
    t.setStyle(TableStyle(st + list(style_extra)))
    return t


def pct(x, d=0):
    return f"{x * 100:.{d}f}%".replace('.', ',').replace('-', '−')


def num(x, d=0):
    s = f"{x:,.{d}f}".replace(',', ' ').replace('.', ',')
    return s


